import { z } from 'zod';
import { exchanges, readHttp, readHttpRequest } from '@atlas/protocol';
import type { HttpContext, HttpError, ReceivedHttp } from '@atlas/protocol';

type ResponseContext = HttpError | { kind: 'success'; body: { dataset_id: string } } | { kind: 'content' | 'reference' };
function binding<R extends z.ZodType, S extends z.ZodType<ResponseContext>>(definition: Parameters<typeof readHttp<R, S>>[0]) {
  return {
    request(incoming: Parameters<typeof readHttpRequest<R, S>>[1], lower?: Parameters<typeof readHttpRequest<R, S>>[2]) { return readHttpRequest(definition, incoming, lower); },
    response(received: ReceivedHttp, context: HttpContext) { return readHttp(definition, received, context); },
  };
}
