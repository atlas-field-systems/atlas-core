import test from 'node:test';
import assert from 'node:assert/strict';
import { Worker } from 'node:worker_threads';
import { fixture, uuid, registration } from './helpers.mjs';
import { recoveryDecision } from '../dist/installation.js';
const run = data => new Promise((resolve, reject) => { const worker = new Worker(new URL('../dist/offline.js', import.meta.url), { workerData: data }); let value; worker.on('message', result => { value = result; }); worker.once('error', reject); worker.once('exit', code => code === 0 ? resolve(value) : reject(new Error('offline_failed'))); });
test('atomic Dataset marker preserves setup, matching recovery regenerates proof, ambiguity refuses', async t => {
  const f = await fixture(t);
  const old = f.core.dataset;
  const registered = registration();
  assert.equal((await f.call('RegisterAsset', registered)).status, 200);
  await f.core.close();
  const dataset = uuid(), actionId = uuid();
  const established = await run({ mode: 'establish', directory: f.directory, settings: f.settings, dataset, action: actionId, hard: false });
  assert.equal(established.established, true);
  const marker = await run({ mode: 'inspect-marker', directory: f.directory });
  assert.equal(marker.dataset, dataset); assert.deepEqual(marker.marker, { dataset, actionId });
  const action = { format: 1, action_id: actionId, installation_id: uuid(), kind: 'reset', old_dataset: old, intended_dataset: dataset, writer: null, image: `sha256:${'0'.repeat(64)}`, phase: 'cleaned', primary_failure: null, cleanup_failure: null };
  assert.equal(recoveryDecision(action, marker, undefined), 'preserve');
  assert.throws(() => recoveryDecision({ ...action, phase: 'established' }, { exists: false, dataset: null, marker: null }, undefined), /repair_required/);
  assert.throws(() => recoveryDecision(action, marker, { action_id: actionId, dataset: uuid(), installation_id: action.installation_id }), /repair_required/);
  await f.restart();
  assert.equal(f.core.dataset, dataset);
  assert.equal((await f.call('GetHealth')).status, 200);
  assert.equal((await f.call('ListAssets', {}, { 'Atlas-Dataset-ID': old })).json.error.code, 'dataset_mismatch');
  assert.equal((await f.call('RegisterAsset', registered)).json.error.code, 'identity_conflict');
  const replacement = { ...registration(), asset_id: registered.asset_id };
  assert.equal((await f.call('RegisterAsset', replacement)).status, 200);
  assert.equal((await f.call('DeleteAsset', { asset_id: replacement.asset_id, request_id: uuid() })).status, 200);
  assert.equal((await f.call('GetHealth', {}, { Authorization: `Bearer ${registered.secret}` })).status, 200);
});
