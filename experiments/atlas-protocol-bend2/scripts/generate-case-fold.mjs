import { readFile, writeFile } from 'node:fs/promises';

const source = new URL(
  '../../../Atlas Protocol/node_modules/unicode-case-folding/',
  import.meta.url,
);
const metadata = JSON.parse(await readFile(new URL('package.json', source), 'utf8'));
if (metadata.version !== '1.1.2') throw new Error('Expected unicode-case-folding 1.1.2');
const { caseFold } = await import(new URL('index.js', source));
const entries = [];
for (let scalar = 0; scalar <= 0x10ffff; scalar++) {
  if (scalar >= 0xd800 && scalar <= 0xdfff) continue;
  const original = String.fromCodePoint(scalar);
  const folded = caseFold(original);
  if (folded !== original) entries.push([scalar, folded]);
}

function tree(start, end, indent) {
  if (start === end) return 'Empty{}';
  const middle = Math.floor((start + end) / 2);
  const [scalar, folded] = entries[middle];
  const padding = ' '.repeat(indent);
  return `Node{${scalar}, ${JSON.stringify(folded)},\n${padding}${tree(start, middle, indent + 2)},\n${padding}${tree(middle + 1, end, indent + 2)}}`;
}
const sourceText = `# Generated by scripts/generate-case-fold.mjs from unicode-case-folding 1.1.2.\nimport Base\n\ntype Table is Data:\n  Empty{}\n  Node{code: U32, folded: String, left: Table, right: Table}\n\ndef table() -> Table:\n  ${tree(0, entries.length, 4)}\n`;
await writeFile(new URL('../unicode-data.bend', import.meta.url), sourceText);
const license = await readFile(new URL('LICENSE', source), 'utf8');
await writeFile(
  new URL('../THIRD_PARTY_NOTICES.md', import.meta.url),
  `# Unicode case folding data\n\nThe generated table in unicode-data.bend uses the mappings from unicode-case-folding 1.1.2.\nIts source is the Unicode Character Database CaseFolding.txt.\nRegenerate it with scripts/generate-case-fold.mjs after installing the original Protocol package's locked dependencies.\n\n${license}`,
);
console.log(`Generated ${entries.length} Unicode case-fold mappings.`);
